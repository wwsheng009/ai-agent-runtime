package remotetools

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// DefaultConfigPath returns ~/.aicli/remote-tools/config.yaml, the file both
// `init` and the first `serve` write.
func DefaultConfigPath() (string, error) {
	tokenPath, err := DefaultRemoteTokenPath()
	if err != nil {
		return "", err
	}
	return filepath.Join(filepath.Dir(tokenPath), "config.yaml"), nil
}

// ConfigSearchPaths returns the config candidates in precedence order, matching
// aicli's convention: the project `.aicli` directory first, then the user one.
func ConfigSearchPaths() []string {
	paths := make([]string, 0, 2)
	if cwd, err := os.Getwd(); err == nil && strings.TrimSpace(cwd) != "" {
		paths = append(paths, filepath.Join(cwd, ".aicli", "remote-tools", "config.yaml"))
	}
	if home, err := remoteToolsHomeDir(); err == nil && strings.TrimSpace(home) != "" {
		userPath := filepath.Join(home, ".aicli", "remote-tools", "config.yaml")
		if len(paths) == 0 || paths[0] != userPath {
			paths = append(paths, userPath)
		}
	}
	return paths
}

// FindConfigFile returns the first existing candidate, or "" when none exists.
func FindConfigFile() string {
	for _, path := range ConfigSearchPaths() {
		if info, err := os.Stat(path); err == nil && !info.IsDir() {
			return path
		}
	}
	return ""
}

// EnsureTokenFile creates a random 0600 token at path when it is missing. An
// existing file is never modified: rotating it would invalidate every client
// that already has the old value.
func EnsureTokenFile(path string) (bool, error) {
	path = strings.TrimSpace(path)
	if path == "" {
		return false, fmt.Errorf("token path is empty")
	}
	if info, err := os.Stat(path); err == nil {
		if info.IsDir() {
			return false, fmt.Errorf("token path %s is a directory", path)
		}
		return false, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("inspect token file %s: %w", path, err)
	}
	raw := make([]byte, 32)
	if _, err := rand.Read(raw); err != nil {
		return false, fmt.Errorf("generate token: %w", err)
	}
	if dir := filepath.Dir(path); dir != "" {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return false, fmt.Errorf("create token dir: %w", err)
		}
	}
	if err := os.WriteFile(path, []byte(hex.EncodeToString(raw)+"\n"), 0o600); err != nil {
		return false, fmt.Errorf("write token file %s: %w", path, err)
	}
	return true, nil
}

// defaultConfigDocument is the minimal auto-init config. Workspace is omitted
// on purpose: a bare `serve` uses the directory it was started from.
type defaultConfigDocument struct {
	HTTP struct {
		Path string `yaml:"path"`
	} `yaml:"http"`
	Gateway *struct {
		UseAICLIConfig bool `yaml:"useAICLIConfig"`
	} `yaml:"gateway,omitempty"`
}

// WriteDefaultConfig creates the auto-init config when the path is free. It
// never overwrites an existing file (os.ErrExist is returned so callers can
// treat that as "already configured").
func WriteDefaultConfig(path string, useAICLIConfig bool) error {
	path = strings.TrimSpace(path)
	if path == "" {
		return fmt.Errorf("config path is empty")
	}
	var document defaultConfigDocument
	document.HTTP.Path = "/mcp"
	if useAICLIConfig {
		document.Gateway = &struct {
			UseAICLIConfig bool `yaml:"useAICLIConfig"`
		}{UseAICLIConfig: true}
	}
	encoded, err := yaml.Marshal(document)
	if err != nil {
		return fmt.Errorf("encode default config: %w", err)
	}
	body := append([]byte("# generated by aicli-remote-tools on first run\n"), encoded...)
	if dir := filepath.Dir(path); dir != "" {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return fmt.Errorf("create config dir: %w", err)
		}
	}
	file, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		return err
	}
	defer file.Close()
	if _, err := file.Write(body); err != nil {
		return fmt.Errorf("write default config: %w", err)
	}
	return nil
}
